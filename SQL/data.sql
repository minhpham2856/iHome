IF EXISTS (SELECT 1 FROM sys.identity_columns WHERE object_id = OBJECT_ID('Contracts') AND last_value IS NOT NULL) DBCC CHECKIDENT ('Contracts', RESEED, 0);
IF EXISTS (SELECT 1 FROM sys.identity_columns WHERE object_id = OBJECT_ID('Tenants') AND last_value IS NOT NULL) DBCC CHECKIDENT ('Tenants', RESEED, 0);
IF EXISTS (SELECT 1 FROM sys.identity_columns WHERE object_id = OBJECT_ID('Services') AND last_value IS NOT NULL) DBCC CHECKIDENT ('Services', RESEED, 0);
IF EXISTS (SELECT 1 FROM sys.identity_columns WHERE object_id = OBJECT_ID('Rooms') AND last_value IS NOT NULL) DBCC CHECKIDENT ('Rooms', RESEED, 0);
IF EXISTS (SELECT 1 FROM sys.identity_columns WHERE object_id = OBJECT_ID('RoomTypes') AND last_value IS NOT NULL) DBCC CHECKIDENT ('RoomTypes', RESEED, 0);
IF EXISTS (SELECT 1 FROM sys.identity_columns WHERE object_id = OBJECT_ID('Buildings') AND last_value IS NOT NULL) DBCC CHECKIDENT ('Buildings', RESEED, 0);
IF EXISTS (SELECT 1 FROM sys.identity_columns WHERE object_id = OBJECT_ID('Properties') AND last_value IS NOT NULL) DBCC CHECKIDENT ('Properties', RESEED, 0);
