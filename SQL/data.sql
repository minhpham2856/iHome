-- ============================================================
-- Reseed identity values safely starting from 1
-- Each CHECKIDENT runs only when the table already has identity usage.
-- Ensures predictable ids (1, 2, 3...) after every re-seed run.
-- ============================================================
IF EXISTS (SELECT 1 FROM sys.identity_columns WHERE object_id = OBJECT_ID('AuditLogs') AND last_value IS NOT NULL) DBCC CHECKIDENT ('AuditLogs', RESEED, 0);
IF EXISTS (SELECT 1 FROM sys.identity_columns WHERE object_id = OBJECT_ID('Payments') AND last_value IS NOT NULL) DBCC CHECKIDENT ('Payments', RESEED, 0);
